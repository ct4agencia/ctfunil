const React = require('react');
const {renderToStaticMarkup} = require('react-dom/server');
const {Block} = require('../src/components/quiz/layers/blocks.tsx');
const ctx = {design:{themeColor:'#0284C7'},name:'',navigate:()=>{},hasFields:false,submitting:false};
const image = {id:'img',type:'image',design:{basis:100,glow:true},content:{image:{src:'https://example.test/transparent.png'}}};
const render = (layer) => renderToStaticMarkup(React.createElement(Block,{layer,ctx,question:''}));
test('glow opcional acompanha o alpha da imagem sem recortar a proporção natural',()=>{
 const html=render(image);
 assert.match(html,/data-image-glow/, 'glow deve existir quando habilitado');
 assert.match(html,/mask-image:url\(&quot;https:\/\/example.test\/transparent.png&quot;\)/);
 assert.match(html,/conic-gradient/);
 assert.match(html,/height:auto/);
 assert.doesNotMatch(html,/object-cover|aspect-ratio:4 \/ 5/);
 assert.doesNotMatch(render({...image,design:{basis:62,glow:false}}),/data-image-glow/);
 assert.match(render({...image,design:{basis:62,glow:false}}),/width:62%/);
});
const LayersRunner = require('../src/components/quiz/layers/LayersRunner.tsx').default;
test('hero declarativo preserva HTML, design e ordem dos blocos sem mudar o hero legado',()=>{
 const layers=[{id:'h',type:'text',design:{basis:100},content:{text:'<h1 style="font-weight:700">Sua apostila está quase <span style="color:#0284C7">liberada!</span> 🎁</h1>'}},image,{id:'card',type:'card',content:{text:'Antes de enviar seu material,'}},{id:'b',type:'button',content:{label:'COMEÇAR',destination:'next'}}];
 const f={slug:'any-slug',name:'Generic',settings:{engine:'layers',design:{presetTelas:'resina'}},steps:[{id:'prep',heroLayout:'blocks',layers}]};
 const html=renderToStaticMarkup(React.createElement(LayersRunner,{funnel:f,preview:true}));
 assert.match(html,/data-hero-blocks/, 'opção deve usar hero declarativo');
 assert.match(html,/<h1 style="font-weight:700">Sua apostila/);
 assert.ok(html.indexOf('liberada!')<html.indexOf('transparent.png'));
 assert.ok(html.indexOf('transparent.png')<html.indexOf('Antes de enviar'));
 assert.ok(html.indexOf('Antes de enviar')<html.indexOf('COMEÇAR'));
 assert.doesNotMatch(html,/text-transform:uppercase/);
 const legacy=renderToStaticMarkup(React.createElement(LayersRunner,{funnel:{...f,steps:[{id:'prep',layers}]},preview:true}));
 assert.match(legacy,/text-transform:uppercase/);
 assert.doesNotMatch(legacy,/data-hero-blocks/);
});
